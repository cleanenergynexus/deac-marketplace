"""Builds the DEAC logo and icon files from the source PNGs in scripts/brand-src.

Run: python3 scripts/brand-assets.py  (needs Pillow). Writes public/brand/*, app/icon.png,
app/apple-icon.png, app/favicon.ico and lib/brand-assets.ts (base64 copies for PDF/PowerPoint export).
"""
import base64, io, os
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "scripts", "brand-src")
BG = (247, 246, 242)
NAVY = (10, 28, 66)
BLUE = (31, 107, 255)


def knockout(img, white=False):
    """Off-white background -> transparent. white=True recolors navy to white (for dark backgrounds)."""
    img = img.convert("RGB")
    out = Image.new("RGBA", img.size)
    src, dst = img.load(), out.load()
    for y in range(img.height):
        for x in range(img.width):
            r, g, b = src[x, y]
            # Coverage from the red channel: navy and blue are both far from the background there.
            a = max(0.0, min(1.0, (BG[0] - r) / (BG[0] - 20)))
            if a < 0.04:
                dst[x, y] = (0, 0, 0, 0)
                continue
            blue = b - r > 120 * a  # the accent tile
            color = BLUE if blue else ((255, 255, 255) if white else NAVY)
            dst[x, y] = (*color, round(255 * min(1.0, a / 0.9)))
    return out


def crop(img, pad):
    box = img.getbbox()
    w, h = box[2] - box[0], box[3] - box[1]
    p = round(max(w, h) * pad)
    return img.crop((box[0] - p, box[1] - p, box[2] + p, box[3] + p))


def save_png(img, path, width=None):
    if width:
        img = img.resize((width, round(img.height * width / img.width)), Image.LANCZOS)
    img.save(path, optimize=True)
    return img


logo_src = Image.open(os.path.join(SRC, "deac-logo-source.png"))
pub = os.path.join(ROOT, "public", "brand")
os.makedirs(pub, exist_ok=True)

logo = crop(knockout(logo_src), 0.02)
logo_white = crop(knockout(logo_src, white=True), 0.02)
save_png(logo, os.path.join(pub, "deac-logo.png"), 1200)
save_png(logo_white, os.path.join(pub, "deac-logo-white.png"), 1200)

# The mark alone: the left square of the wordmark (crisp vector-like edges).
lb = logo.getbbox()
mark = logo.crop((lb[0], lb[1], lb[0] + (lb[3] - lb[1]), lb[3]))
mark_white = logo_white.crop((lb[0], lb[1], lb[0] + (lb[3] - lb[1]), lb[3]))
save_png(mark, os.path.join(pub, "deac-mark.png"), 512)
save_png(mark_white, os.path.join(pub, "deac-mark-white.png"), 512)

# App icons from the favicon artwork, cleaned to flat colours on the off-white background.
fav = knockout(Image.open(os.path.join(SRC, "deac-favicon-source.png")))
fav = crop(fav, 0.08)
side = max(fav.size)
square = Image.new("RGBA", (side, side), (*BG, 255))
square.alpha_composite(fav, ((side - fav.width) // 2, (side - fav.height) // 2))
save_png(square, os.path.join(ROOT, "app", "icon.png"), 512)
save_png(square.convert("RGB"), os.path.join(ROOT, "app", "apple-icon.png"), 180)
square.save(os.path.join(ROOT, "app", "favicon.ico"), sizes=[(16, 16), (32, 32), (48, 48)])

# Base64 copies for the Document Wizard exports (serverless functions can't rely on reading public/).
def b64(img, width):
    img = img.resize((width, round(img.height * width / img.width)), Image.LANCZOS)
    buf = io.BytesIO()
    img.save(buf, "PNG", optimize=True)
    return base64.b64encode(buf.getvalue()).decode(), img.size

entries = {"logo": b64(logo, 900), "logoWhite": b64(logo_white, 900), "mark": b64(mark, 256), "markWhite": b64(mark_white, 256)}
with open(os.path.join(ROOT, "lib", "brand-assets.ts"), "w") as f:
    f.write("// Generated by scripts/brand-assets.py. Do not edit by hand.\n")
    f.write("// DEAC logo (full wordmark) and mark as base64 PNGs, with transparent backgrounds.\n")
    f.write("export type BrandImage = { base64: string; width: number; height: number };\n\n")
    for k, (data, (w, h)) in entries.items():
        f.write(f'export const {k}: BrandImage = {{ width: {w}, height: {h}, base64: "{data}" }};\n')
print("done")
